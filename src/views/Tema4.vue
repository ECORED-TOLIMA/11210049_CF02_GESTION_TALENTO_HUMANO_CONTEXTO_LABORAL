      h2 4.1 Concepto de asertividad

    p.mt-4(data-aos="fade-right") La asertividad puede entenderse como el punto de equilibrio entre dos estilos comunicativos extremos: la pasividad y la agresividad. La persona pasiva evita expresar sus opiniones y necesidades por temor al rechazo o al conflicto, acumulando frustración y resentimiento que eventualmente deterioran sus relaciones y su bienestar. La persona agresiva, por el contrario, expresa sus ideas y necesidades de manera impositiva, sin considerar los derechos y sentimientos de los demás, lo que genera conflictos y deteriora el clima organizacional.

